from __future__ import annotations

from typing import Protocol
from noetrium_platform.substrate.api import (
    ExactServiceRuntimePort,
    ServiceQuiescenceOutcome,
    ServiceStartOutcome,
    ServiceStopOutcome,
)
from noetrium_platform.substrate.api import ServiceLaunchContract
from noetrium_platform.substrate.api import GpuDeviceStatus, GpuRuntimeSnapshot
from .contracts import (
    ModelAppliedRuntimeIdentity, ModelControlSnapshot, ModelControllerState, ModelDeploymentGeneration, ModelDeploymentLogs, ModelDeploymentSelector,
    ModelDesiredDeployment, ModelDeploymentStatus, ModelDesiredState,
    ModelGpuAllocation, ModelGpuConflict, ModelGpuProcessBinding, ModelLogTail,
)

class ModelServiceRuntimeFactoryPort(Protocol):
    def open(
        self,
        spec: ModelDesiredDeployment,
        contract: ServiceLaunchContract,
        *,
        environment: tuple[tuple[str, str], ...],
        readiness_url: str | None,
    ) -> ExactServiceRuntimePort: ...
    def frozen_contracts(
        self,
        spec: ModelDesiredDeployment,
    ) -> tuple[ServiceLaunchContract, ...]: ...
    def quiesce(
        self,
        spec: ModelDesiredDeployment,
        *,
        contracts: tuple[ServiceLaunchContract, ...],
    ) -> tuple[ServiceQuiescenceOutcome, ...]: ...
    def quiesce_retired(
        self,
        deployment_id: str,
    ) -> tuple[ServiceQuiescenceOutcome, ...]: ...
    def logs(self, contract: ServiceLaunchContract, *, deployment_id: str) -> ModelDeploymentLogs: ...

class ModelDeploymentCatalogPort(Protocol):
    def put_deployment(self, spec: ModelDesiredDeployment) -> ModelDesiredDeployment: ...
    def deployment(self, deployment_id: str) -> ModelDesiredDeployment: ...
    def deployments(self) -> tuple[ModelDesiredDeployment, ...]: ...
    def select(self, selector: ModelDeploymentSelector = ModelDeploymentSelector()) -> tuple[ModelDesiredDeployment, ...]: ...
    def set_desired_state_selected(self, selector: ModelDeploymentSelector, state: ModelDesiredState) -> tuple[ModelDesiredDeployment, ...]: ...
    def set_desired_state(self, deployment_id: str, state: ModelDesiredState) -> ModelDesiredDeployment: ...
    def set_gpu_devices(self, deployment_id: str, gpu_devices: tuple[str, ...]) -> ModelDesiredDeployment: ...
    def retired_deployment_ids(self) -> tuple[str, ...]: ...
    def remove(self, deployment_id: str) -> bool: ...

class ModelDeploymentRuntimePort(Protocol):
    def generation(self, deployment_id: str) -> ModelDeploymentGeneration: ...
    def recover_applied(
        self, generation: ModelDeploymentGeneration
    ) -> ModelDeploymentGeneration: ...
    def start(self, generation: ModelDeploymentGeneration) -> ModelDeploymentStatus: ...
    def stop(self, generation: ModelDeploymentGeneration) -> ModelDeploymentStatus: ...
    def shutdown(self, generation: ModelDeploymentGeneration) -> ModelDeploymentStatus: ...
    def restart(self, generation: ModelDeploymentGeneration) -> ModelDeploymentStatus: ...
    def status(self, deployment_id: str) -> ModelDeploymentStatus: ...
    def applied_identity(self, deployment_id: str) -> ModelAppliedRuntimeIdentity: ...
    def reconcile_retired_orphans(self) -> tuple[ServiceQuiescenceOutcome, ...]: ...
    def remove_deployment(self, generation: ModelDeploymentGeneration) -> bool: ...

class ModelFleetRuntimePort(Protocol):
    def status_all(self) -> tuple[ModelDeploymentStatus, ...]: ...
    def reconcile(self) -> tuple[ModelDeploymentStatus, ...]: ...
    def reset_auto_recovery(self, deployment_id: str) -> bool: ...
    def start_all(self) -> tuple[ModelDeploymentStatus, ...]: ...
    def stop_all(self) -> tuple[ModelDeploymentStatus, ...]: ...
    def shutdown_all(self) -> tuple[ModelDeploymentStatus, ...]: ...
    def remove_selected(self, selector: ModelDeploymentSelector) -> tuple[str, ...]: ...

class ModelDeploymentLogPort(Protocol):
    def logs(self, deployment_id: str) -> ModelDeploymentLogs: ...
    def tail_logs(self, deployment_id: str, *, stream: str = "stderr", max_bytes: int = 8192) -> ModelLogTail: ...

class ModelControllerStatePort(Protocol):
    def read(self) -> ModelControllerState | None: ...
    def write(self, state: ModelControllerState) -> ModelControllerState: ...

class ModelControllerStopPort(Protocol):
    def wait(self, timeout: float | None = None) -> bool: ...

class ModelReconcileControllerPort(Protocol):
    def run(self, *, interval_seconds: float, stop: ModelControllerStopPort, max_cycles: int | None = None) -> ModelControllerState: ...
    def snapshot(self) -> ModelControllerState | None: ...

class ModelResourceViewPort(Protocol):
    def deployment_cut(
        self,
    ) -> tuple[
        tuple[ModelDesiredDeployment, ...],
        tuple[ModelDeploymentStatus, ...],
    ]: ...
    def gpu_allocations(self) -> tuple[ModelGpuAllocation, ...]: ...
    def gpu_conflicts(self) -> tuple[ModelGpuConflict, ...]: ...
    def gpu_runtime(self) -> GpuRuntimeSnapshot: ...
    def gpu_candidates(self, *, count: int = 1, min_free_memory_mb: int = 0, max_utilization_percent: int = 100) -> tuple[GpuDeviceStatus, ...]: ...
    def gpu_process_bindings(self) -> tuple[ModelGpuProcessBinding, ...]: ...
    def snapshot(self) -> ModelControlSnapshot: ...

__all__ = [
    "ModelControllerStatePort", "ModelControllerStopPort", "ModelDeploymentCatalogPort", "ModelDeploymentLogPort",
    "ModelDeploymentRuntimePort", "ModelFleetRuntimePort", "ModelReconcileControllerPort", "ModelResourceViewPort",
    "ModelServiceRuntimeFactoryPort",
]
