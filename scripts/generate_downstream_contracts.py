_CONVENIENCE_EXCLUDED_NAMES = frozenset({"CONTRACT", "contract"})


@dataclass(frozen=True)
class ApiModuleSurface:
    module: str
    source: str
    symbols: tuple[str, ...]


@dataclass(frozen=True)
class SystemSurface:
    system_key: str
    package_prefix: str
    authority: str
    owns: str
    must_not_own: str
    requires: tuple[str, ...]
    provides: tuple[str, ...]
    downstream_surface: str
    api_modules: tuple[ApiModuleSurface, ...]
    facade_module: str | None


def _scope_name_from_alias(alias: ast.alias) -> str:
    return alias.asname or alias.name.split(".")[-1]


def _safe_name_predicate(node: ast.AST, *, variable: str, value: str) -> bool:
    """Evaluate the narrow predicate grammar used by declarative ``__all__`` builders."""
    if isinstance(node, ast.BoolOp):
        rows = tuple(_safe_name_predicate(row, variable=variable, value=value) for row in node.values)
        if isinstance(node.op, ast.Or):
            return any(rows)
        if isinstance(node.op, ast.And):
            return all(rows)
        raise ValueError("unsupported boolean operator in __all__ predicate")
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
        return not _safe_name_predicate(node.operand, variable=variable, value=value)
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
        receiver = node.func.value
        if not isinstance(receiver, ast.Name) or receiver.id != variable:
            raise ValueError("unsupported __all__ predicate receiver")
        if node.func.attr not in {"startswith", "endswith"} or len(node.args) != 1 or node.keywords:
            raise ValueError("unsupported __all__ predicate call")
        argument = ast.literal_eval(node.args[0])
        if not isinstance(argument, (str, tuple)):
            raise ValueError("unsupported __all__ predicate argument")
        method = getattr(value, node.func.attr)
        return bool(method(argument))
    if isinstance(node, ast.Compare) and len(node.ops) == 1 and len(node.comparators) == 1:
        left = value if isinstance(node.left, ast.Name) and node.left.id == variable else ast.literal_eval(node.left)
        right_node = node.comparators[0]
        right = value if isinstance(right_node, ast.Name) and right_node.id == variable else ast.literal_eval(right_node)
        if isinstance(node.ops[0], ast.Eq):
            return left == right
        if isinstance(node.ops[0], ast.NotEq):
            return left != right
    raise ValueError("unsupported __all__ predicate")


def _string_sequence(
    node: ast.AST,
    *,
    sequences: dict[str, tuple[str, ...]],
    scope_names: tuple[str, ...],
) -> tuple[str, ...]:
    if isinstance(node, ast.Name):
        try:
            return sequences[node.id]
        except KeyError as exc:
            raise ValueError(f"unknown __all__ sequence {node.id}") from exc
    if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        rows: list[str] = []
        for item in node.elts:
            if isinstance(item, ast.Starred):
                rows.extend(_string_sequence(item.value, sequences=sequences, scope_names=scope_names))
                continue
            value = ast.literal_eval(item)
            if not isinstance(value, str):
                raise ValueError("__all__ contains a non-string value")
            rows.append(value)
        return tuple(rows)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return (
            *_string_sequence(node.left, sequences=sequences, scope_names=scope_names),
            *_string_sequence(node.right, sequences=sequences, scope_names=scope_names),
        )
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
        if node.func.id not in {"tuple", "list"} or len(node.args) != 1 or node.keywords:
            raise ValueError("unsupported __all__ sequence constructor")
        return _string_sequence(node.args[0], sequences=sequences, scope_names=scope_names)
    if isinstance(node, (ast.ListComp, ast.GeneratorExp)):
        if len(node.generators) != 1:
            raise ValueError("unsupported __all__ comprehension")
        generator = node.generators[0]
        if generator.is_async or not isinstance(generator.target, ast.Name):
            raise ValueError("unsupported __all__ comprehension target")
        variable = generator.target.id
        if not (
            isinstance(generator.iter, ast.Call)
            and isinstance(generator.iter.func, ast.Name)
            and generator.iter.func.id == "globals"
            and not generator.iter.args
            and not generator.iter.keywords
        ):
            raise ValueError("unsupported __all__ comprehension iterable")
        if not isinstance(node.elt, ast.Name) or node.elt.id != variable:
            raise ValueError("unsupported __all__ comprehension projection")
        result: list[str] = []
        for name in scope_names:
            if all(_safe_name_predicate(cond, variable=variable, value=name) for cond in generator.ifs):
                result.append(name)
        return tuple(result)
    value = ast.literal_eval(node)
    if isinstance(value, (list, tuple)) and all(isinstance(item, str) for item in value):
        return tuple(value)
    raise ValueError("unsupported __all__ expression")


def _declared_all(tree: ast.Module) -> tuple[str, ...] | None:
    """Resolve declarative ``__all__`` updates without importing project code."""
    sequences: dict[str, tuple[str, ...]] = {}
    scope_names: list[str] = []
    saw_all = False

    def remember(name: str) -> None:
        if name not in scope_names:
            scope_names.append(name)

    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            remember(node.name)
            continue
        if isinstance(node, ast.Import):
            for alias in node.names:
                remember(_scope_name_from_alias(alias))
            continue
        if isinstance(node, ast.ImportFrom):
            if node.module == "__future__":
                continue
            for alias in node.names:
                if alias.name != "*":
                    remember(_scope_name_from_alias(alias))
            continue
        if isinstance(node, ast.Assign):
            simple_targets = [target.id for target in node.targets if isinstance(target, ast.Name)]
            for target in simple_targets:
                if target != "__all__":
                    remember(target)
            try:
                resolved = _string_sequence(
                    node.value,
                    sequences=sequences,
                    scope_names=tuple(scope_names),
                )
            except (ValueError, TypeError, SyntaxError):
                resolved = None
            for target in simple_targets:
                if resolved is not None:
                    sequences[target] = resolved
                elif target in sequences:
                    sequences.pop(target)
                if target == "__all__":
                    saw_all = True
            continue
        if isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name):
            if node.target.id == "__all__" and isinstance(node.op, ast.Add):
                saw_all = True
                try:
                    extension = _string_sequence(
                        node.value,
                        sequences=sequences,
                        scope_names=tuple(scope_names),
                    )
                    sequences["__all__"] = (*sequences.get("__all__", ()), *extension)
                except (ValueError, TypeError, SyntaxError):
                    sequences.pop("__all__", None)
            continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            call = node.value
            if isinstance(call.func, ast.Attribute) and isinstance(call.func.value, ast.Name):
                if call.func.value.id == "__all__" and call.func.attr in {"extend", "append"}:
                    saw_all = True
                    try:
                        if call.func.attr == "extend" and len(call.args) == 1:
                            extension = _string_sequence(
                                call.args[0], sequences=sequences, scope_names=tuple(scope_names)
                            )
                        elif call.func.attr == "append" and len(call.args) == 1:
                            value = ast.literal_eval(call.args[0])
                            if not isinstance(value, str):
                                raise ValueError("__all__.append requires string")
                            extension = (value,)
                        else:
                            raise ValueError("unsupported __all__ mutation")
                        sequences["__all__"] = (*sequences.get("__all__", ()), *extension)
                    except (ValueError, TypeError, SyntaxError):
                        sequences.pop("__all__", None)
    if not saw_all:
        return None
    resolved = sequences.get("__all__")
    if resolved is None:
        raise RuntimeError("declared __all__ cannot be resolved statically")
    return tuple(dict.fromkeys(resolved))


def _public_symbols(path: Path) -> tuple[str, ...]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    declared = _declared_all(tree)
    if declared is not None:
        return declared
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.name.startswith("_"):
                names.append(node.name)
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            if module == "__future__":
                continue
            if node.level == 0 and not (
                module.startswith("noetrium_platform")
                or module.startswith("components")
                or module.startswith("orchestration")
            ):
                continue
            for alias in node.names:
                if alias.name == "*":
                    continue
                name = alias.asname or alias.name.split(".")[-1]
                if not name.startswith("_"):
                    names.append(name)
    return tuple(dict.fromkeys(names))

def _package_dir(root: Path, package_prefix: str) -> Path:
    return root.joinpath(*package_prefix.split("."))


def _module_name(package_prefix: str, api_root: Path, path: Path) -> str:
    relative = path.relative_to(api_root)
    parts = list(relative.parts)
    if parts[-1] == "__init__.py":
        parts = parts[:-1]
    else:
        parts[-1] = Path(parts[-1]).stem
    suffix = ".".join(part for part in parts if part)
    return f"{package_prefix}.api" + (f".{suffix}" if suffix else "")


def _api_modules(root: Path, package_prefix: str) -> tuple[ApiModuleSurface, ...]:
    package = _package_dir(root, package_prefix)
    api_root = package / "api"
    candidates: list[Path] = []
    if (package / "api.py").is_file():
        candidates.append(package / "api.py")
    if api_root.is_dir():
        candidates.extend(sorted(api_root.rglob("*.py")))
    rows: list[ApiModuleSurface] = []
    seen: set[str] = set()
    for path in candidates:
        module = (
            f"{package_prefix}.api"
            if path.name == "api.py"
            else _module_name(package_prefix, api_root, path)
        )
        if module in seen:
            continue
        seen.add(module)
        symbols = _public_symbols(path)
        if symbols:
            rows.append(ApiModuleSurface(module, path.relative_to(root).as_posix(), symbols))
    return tuple(rows)


def _facade_slug(system_key: str) -> str:
    return _SAFE.sub("__", system_key).strip("_.") or "system"


def _digest(value: object) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def build_surfaces(root: Path) -> tuple[SystemSurface, ...]:
    registry_path = root / "noetrium_platform/foundation/governance/system_registry/catalog.json"
    catalog = json.loads(registry_path.read_text(encoding="utf-8"))
    if not isinstance(catalog, dict):
        raise ValueError("canonical system registry must be an object")
    rows: list[SystemSurface] = []
    for system_key, descriptor in catalog.items():
        if not isinstance(descriptor, dict):
            raise ValueError(f"invalid system descriptor: {system_key}")
        downstream_surface = str(descriptor.get("downstream_surface", "public"))
        modules = (
            ()
            if downstream_surface == "metadata_only"
            else _api_modules(root, descriptor["package_prefix"])
        )
        rows.append(SystemSurface(
            system_key=system_key,
            package_prefix=descriptor["package_prefix"],
            authority=descriptor["authority"],
            owns=descriptor["owns"],
            must_not_own=descriptor["must_not_own"],
            requires=tuple(descriptor["requires"]),
            provides=tuple(descriptor["provides"]),
            downstream_surface=downstream_surface,
            api_modules=modules,
            facade_module=(
                f"noetrium.contracts.systems.{_facade_slug(system_key)}"
            ),
        ))
    return tuple(rows)


def _aliased_symbols(surface: SystemSurface) -> list[tuple[str, str, str]]:
    """Return (module, source_name, facade_name), preserving collisions."""
    result: list[tuple[str, str, str]] = []
    used: set[str] = set()
    for api in surface.api_modules:
        module_slug = _SAFE.sub("_", api.module.rsplit(".", 1)[-1])
        for name in api.symbols:
            facade_name = name
            if facade_name in used:
                facade_name = f"{module_slug}__{name}"
                serial = 2
                while facade_name in used:
                    facade_name = f"{module_slug}{serial}__{name}"
                    serial += 1
            used.add(facade_name)
            result.append((api.module, name, facade_name))
    return result


def render_facade(surface: SystemSurface) -> str:
    imports: dict[str, list[tuple[str, str]]] = {}
    for module, source_name, facade_name in _aliased_symbols(surface):
        imports.setdefault(module, []).append((source_name, facade_name))
    lines = [
        f'""" {_MARKER}.',
        f"System: {surface.system_key}",
        f"Authority: {surface.authority}",
        f"Downstream surface: {surface.downstream_surface}",
        f"API exports: {'available' if surface.api_modules else 'none (metadata-only facade)'}",
        "This module is regenerated from the canonical registry and API exports.",
        '"""',
        "",
    ]
    for module in sorted(imports):
        lines.append(f"from {module} import (")
        for source_name, facade_name in imports[module]:
            suffix = "" if source_name == facade_name else f" as {facade_name}"
            lines.append(f"    {source_name}{suffix},")
        lines.extend((")", ""))
    names = [facade_name for _, _, facade_name in _aliased_symbols(surface)]
    lines.append(f"SYSTEM_KEY = {surface.system_key!r}")
    lines.append(f"PACKAGE_PREFIX = {surface.package_prefix!r}")
    lines.append(f"__all__ = {tuple(names)!r}")
    lines.append("")
    return "\n".join(lines)


def _convenience_surface_keys(
    surfaces: tuple[SystemSurface, ...],
    specs: tuple[tuple[str, bool], ...],
) -> tuple[str, ...]:
    keys: list[str] = []
    available = {surface.system_key for surface in surfaces}
    for root, subtree in specs:
        if root not in available:
            raise ValueError(f"convenience facade references unknown system root: {root}")
        for surface in surfaces:
            key = surface.system_key
            if key == root or (subtree and key.startswith(root + "/")):
                if key not in keys:
                    keys.append(key)
    return tuple(keys)


def render_convenience_facade(
    name: str,
    surfaces: tuple[SystemSurface, ...],
) -> str:
    specs = _CONVENIENCE_FACADES[name]
    keys = _convenience_surface_keys(surfaces, specs)
    surface_index = {surface.system_key: surface for surface in surfaces}
    canonical = _CONVENIENCE_CANONICAL_OWNERS.get(name, {})
    for symbol, owner in canonical.items():
        if owner not in keys:
            raise ValueError(
                f"convenience canonical owner is outside facade roots: {name}.{symbol} -> {owner}"
            )
    lines = [
        f'""" {_MARKER}.',
        f"Convenience facade: {name}",
        "Sources are selected by canonical registry roots and declared compatibility planes; symbol lists are never hand-maintained.",
        '"""',
        "from __future__ import annotations",
        "",
    ]
    source_rows: list[tuple[str, str]] = []
    for index, key in enumerate(keys):
        module = surface_index[key].facade_module
        alias = f"_surface_{index}"
        lines.append(f"from {module.rsplit('.', 1)[0]} import {module.rsplit('.', 1)[1]} as {alias}")
        source_rows.append((key, alias))
    for index, (key, plane) in enumerate(_CONVENIENCE_EXTRA_PLANES.get(name, ())):
        if key not in surface_index:
            raise ValueError(f"convenience extra references unknown system root: {key}")
        package = surface_index[key].package_prefix
        alias = f"_extra_{index}"
        lines.append(f"from {package} import {plane} as {alias}")
        source_rows.append((f"{key}/{plane}", alias))
    lines.extend([
        "",
        f"_SOURCES = {tuple(source_rows)!r}",
        f"_CANONICAL_OWNERS = {canonical!r}",
        f"_EXCLUDED = frozenset({tuple(sorted(_CONVENIENCE_EXCLUDED_NAMES))!r})",
        "_owners: dict[str, str] = {}",
        "_exports: list[str] = []",
        "",
        "def _qualified(system_key: str, name: str) -> str:",
        "    return system_key.replace('/', '__').replace('-', '_') + '__' + name",
        "",
        "for _system_key, _module_name in _SOURCES:",
        "    _module = globals()[_module_name]",
        "    for _name in _module.__all__:",
        "        if '__' in _name or _name in _EXCLUDED:",
        "            continue",
        "        _value = getattr(_module, _name)",
        "        if _name not in _owners:",
        "            globals()[_name] = _value",
        "            _owners[_name] = _system_key",
        "            _exports.append(_name)",
        "            continue",
        "        _owner = _owners[_name]",
        "        _current = globals()[_name]",
        "        if _current is _value:",
        "            continue",
        "        _owner_alias = _qualified(_owner, _name)",
        "        _new_alias = _qualified(_system_key, _name)",
        "        if _owner_alias not in globals():",
        "            globals()[_owner_alias] = _current",
        "            _exports.append(_owner_alias)",
        "        globals()[_new_alias] = _value",
        "        if _new_alias not in _exports:",
        "            _exports.append(_new_alias)",
        "        _canonical = _CANONICAL_OWNERS.get(_name)",
        "        if _canonical is None:",
        "            raise RuntimeError(",
        "                f'convenience facade symbol collision requires canonical owner: {_name}: '",
        "                f'{_owner} vs {_system_key}'",
        "            )",
        "        if _canonical == _system_key:",
        "            globals()[_name] = _value",
        "            _owners[_name] = _system_key",
        "        elif _canonical != _owner:",
        "            raise RuntimeError(",
        "                f'invalid canonical owner for {_name}: {_canonical}; observed {_owner}, {_system_key}'",
        "            )",
        "",
        "__all__ = tuple(_exports)",
        "",
        "del _exports, _owners",
        "",
    ])
    return "\n".join(lines)


def render_root_contract_init(root: Path) -> str:
    json_symbols = _public_symbols(root / "noetrium/contracts/json.py")
    sources = ("json", "discovery", *_CONVENIENCE_FACADES.keys())
    lines = [
        f'""" {_MARKER}.',
        "Stable aggregate contract facade derived from generated contract families.",
        '"""',
        "from __future__ import annotations",
        "",
    ]
    for index, name in enumerate(sources):
        lines.append(f"from . import {name} as _source_{index}")
    lines.extend([
        "from .systems import SYSTEM_FACADES, SYSTEM_KEYS",
        "",
        f"_SOURCE_NAMES = {sources!r}",
        f"_JSON_CANONICAL = {tuple(json_symbols)!r}",
        "_SOURCES = tuple((_name, globals()[f'_source_{_index}']) for _index, _name in enumerate(_SOURCE_NAMES))",
        "_owners: dict[str, str] = {}",
        "_exports: list[str] = []",
        "",
        "def _qualified(owner: str, name: str) -> str:",
        "    return owner.replace('-', '_') + '__' + name",
        "",
        "for _owner_name, _module in _SOURCES:",
        "    for _name in _module.__all__:",
        "        _value = getattr(_module, _name)",
        "        if _name not in _owners:",
        "            globals()[_name] = _value",
        "            _owners[_name] = _owner_name",
        "            _exports.append(_name)",
        "            continue",
        "        _previous_owner = _owners[_name]",
        "        _current = globals()[_name]",
        "        if _current is _value:",
        "            continue",
        "        if _name in _JSON_CANONICAL:",
        "            if _previous_owner == 'json':",
        "                continue",
        "            if _owner_name == 'json':",
        "                globals()[_name] = _value",
        "                _owners[_name] = 'json'",
        "                continue",
        "        _old_alias = _qualified(_previous_owner, _name)",
        "        _new_alias = _qualified(_owner_name, _name)",
        "        if _old_alias not in globals():",
        "            globals()[_old_alias] = _current",
        "            _exports.append(_old_alias)",
        "        globals()[_new_alias] = _value",
        "        if _new_alias not in _exports:",
        "            _exports.append(_new_alias)",
        "        raise RuntimeError(",
        "            f'top-level contract symbol collision requires explicit canonical source: {_name}: '",
        "            f'{_previous_owner} vs {_owner_name}'",
        "        )",
        "",
        "__all__ = tuple(dict.fromkeys((*_exports, 'SYSTEM_FACADES', 'SYSTEM_KEYS')))",
        "",
        "del _exports, _owners",
        "",
    ])
    return "\n".join(lines)


def render_init(surfaces: tuple[SystemSurface, ...]) -> str:
    mapping = {
        surface.system_key: surface.facade_module
        for surface in surfaces
    }
    lines = [
        f'""" {_MARKER}.',
        "One generated system facade exists for every registered system; API exports are included when available.",
        '"""',
        "",
        f"SYSTEM_FACADES = {mapping!r}",
        f"SYSTEM_KEYS = {tuple(surface.system_key for surface in surfaces)!r}",
        "",
        '__all__ = ["SYSTEM_FACADES", "SYSTEM_KEYS"]',
        "",
    ]
    return "\n".join(lines)


def render_catalog(root: Path, surfaces: tuple[SystemSurface, ...]) -> bytes:
    registry = json.loads(
        (root / "noetrium_platform/foundation/governance/system_registry/catalog.json")
        .read_text(encoding="utf-8")
    )
    topology_digest = _digest(registry)
    document: dict[str, Any] = {
        "schema": SCHEMA,
        "generator": "scripts/generate_downstream_contracts.py",
        "topology_digest": topology_digest,
        "systems": [],
    }
    for surface in surfaces:
        row: dict[str, Any] = {
            "system_key": surface.system_key,
            "package_prefix": surface.package_prefix,
            "authority": surface.authority,
            "owns": surface.owns,
            "must_not_own": surface.must_not_own,
            "requires": list(surface.requires),
            "provides": list(surface.provides),
            "downstream_surface": surface.downstream_surface,
            "facade_module": surface.facade_module,
            "api_modules": [
                {"module": api.module, "source": api.source, "symbols": list(api.symbols)}
                for api in surface.api_modules
            ],
        }
        row["interface_digest"] = _digest(row)
        document["systems"].append(row)
    document["catalog_digest"] = _digest(document)
    return (json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")


def _domain_rows(surfaces: tuple[SystemSurface, ...]) -> tuple[tuple[str, int, int, int], ...]:
    grouped: dict[str, list[int]] = {}
    for surface in surfaces:
        domain = surface.system_key.split("/", 1)[0]
        row = grouped.setdefault(domain, [0, 0, 0])
        row[0] += 1
        row[1] += len(surface.api_modules)
        row[2] += sum(len(api.symbols) for api in surface.api_modules)
    return tuple(
        (domain, values[0], values[1], values[2])
        for domain, values in sorted(grouped.items())
    )


def render_markdown(root: Path, surfaces: tuple[SystemSurface, ...]) -> bytes:
    registry = json.loads(
        (root / "noetrium_platform/foundation/governance/system_registry/catalog.json")
        .read_text(encoding="utf-8")
    )
    domains = _domain_rows(surfaces)
    total_modules = sum(len(surface.api_modules) for surface in surfaces)
    total_symbols = sum(
        len(api.symbols) for surface in surfaces for api in surface.api_modules
    )
    lines = [
        "# Noetrium downstream capability catalog",
        "",
        "This file is generated from the canonical system registry and public API exports.",
        "Do not edit it manually; run python scripts/update_generated_docs.py.",
        "",
        "## How downstream projects use Noetrium",
        "",
        "1. Find the capability in noetrium/contracts/downstream_capability_catalog.json.",
        "2. Use its facade_module and import only that generated public facade.",
        "3. Inject the listed ports during composition; do not import noetrium_platform implementation modules.",
        "4. Run python scripts/update_generated_docs.py after changing a registry descriptor or public API export.",
        "",
        "Example:",
        "",
        "    from noetrium.contracts.systems.environment__minecraft import MinecraftBridgePort",
        "    from noetrium.contracts.systems.participant__agent import AgentMemoryPort",
        "",
        "    def compose(bridge: MinecraftBridgePort, memory: AgentMemoryPort) -> None:",
        "        ...",
        "",
        f"- Registered systems: {len(surfaces)}",
        f"- Public API modules: {total_modules}",
        f"- Public symbols: {total_symbols}",
        f"- Registry digest: {_digest(registry)}",
        "",
        "## Capability domains",
        "",
        "| Domain | Systems | API modules | Symbols |",
        "| --- | ---: | ---: | ---: |",
    ]
    for domain, system_count, module_count, symbol_count in domains:
        lines.append(f"| {domain} | {system_count} | {module_count} | {symbol_count} |")
    lines.extend(["", "## System surfaces", ""])
    for surface in surfaces:
        requires = ", ".join(surface.requires) or "none"
        provides = ", ".join(surface.provides) or "none"
        lines.extend([
            f"### {surface.system_key}",
            "",
            f"- Package: {surface.package_prefix}",
            f"- Authority: {surface.authority}",
            f"- Owns: {surface.owns}",
            f"- Must not own: {surface.must_not_own}",
            f"- Requires: {requires}",
            f"- Provides: {provides}",
            f"- Downstream surface: {surface.downstream_surface}",
            f"- Facade: {surface.facade_module}" if surface.facade_module else "- Facade: none (no exported API symbols)",
            "",
        ])
        if surface.api_modules:
            lines.append("#### API modules")
            lines.append("")
            for api in surface.api_modules:
                symbols = ", ".join(api.symbols)
                lines.append(f"- {api.module} ?w^~)?t {symbols}")
            lines.append("")
    return ("\n".join(lines) + "\n").encode("utf-8")


def render_readme_interface_block(surfaces: tuple[SystemSurface, ...]) -> str:
    domains = _domain_rows(surfaces)
    total_modules = sum(len(surface.api_modules) for surface in surfaces)
    total_symbols = sum(
        len(api.symbols) for surface in surfaces for api in surface.api_modules
    )
    lines = [
        README_BLOCK_START,
        "### Public interface catalog",
        "",
        "Noetrium is a general-purpose research-systems platform for long-running agents, stateful environments, model providers, experiments, and other evidence-driven workloads. The complete downstream interface is generated from the canonical registry, so the list stays synchronized with the code.",
        "",
        f"- {len(surfaces)} registered system surfaces; {total_modules} public API modules; {total_symbols} public symbols.",
        "- Full machine-readable catalog: noetrium/contracts/downstream_capability_catalog.json",
        "- Full human-readable catalog: docs/architecture/DOWNSTREAM_CAPABILITY_CATALOG.md",
        "- Import rule: use noetrium.contracts.systems.<system-slug>; do not import noetrium_platform implementation modules.",
        "",
        "| Capability domain | Registered surfaces |",
        "| --- | ---: |",
    ]
    for domain, system_count, _module_count, _symbol_count in domains:
        lines.append(f"| {domain} | {system_count} |")
    lines.extend([
        "",
        "Discover a capability in the catalog, import its generated facade, and inject its typed ports in downstream composition:",
        "",
        "    from noetrium.contracts.systems.environment__minecraft import MinecraftBridgePort",
        "    from noetrium.contracts.systems.participant__agent import AgentMemoryPort",
        "",
        "After changing a registry descriptor or public API export, run python scripts/update_generated_docs.py; CI fails on generated-surface or README drift.",
        README_BLOCK_END,
    ])
    return "\n".join(lines)


def _readme_paths(root: Path) -> tuple[Path, ...]:
    manifest_path = root / "docs/readme/LANGUAGES.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        return tuple(root / row["file"] for row in manifest["languages"])
    return tuple(sorted(root.glob("README*.md")))


def _replace_readme_interface_block(text: str, block: str) -> str:
    pattern = re.compile(
        re.escape(README_BLOCK_START) + r".*?" + re.escape(README_BLOCK_END),
        re.S,
    )
    if pattern.search(text):
        return pattern.sub(block, text, count=1)
    anchor = "<!-- readme-section:architecture -->"
    if anchor not in text:
        raise ValueError("README is missing architecture section anchor")
    return text.replace(anchor, block + "\n\n" + anchor, 1)

def _write_or_check(path: Path, content: bytes, check: bool) -> bool:
    current = path.read_bytes() if path.is_file() else None
    if check:
        return current == content
    path.parent.mkdir(parents=True, exist_ok=True)
    if current != content:
        path.write_bytes(content)
    return True


def generate(root: Path, *, check: bool = False) -> int:
    surfaces = build_surfaces(root)
    facade_root = root / "noetrium/contracts/systems"
    catalog_path = root / "noetrium/contracts/downstream_capability_catalog.json"
    markdown_path = root / "docs/architecture/DOWNSTREAM_CAPABILITY_CATALOG.md"
    topology_path = root / "docs/architecture/VNEXT_SYSTEM_CATALOG.json"
    topology_source = root / "noetrium_platform/foundation/governance/system_registry/catalog.json"
    expected: dict[Path, bytes] = {
        facade_root / "__init__.py": render_init(surfaces).encode("utf-8"),
        catalog_path: render_catalog(root, surfaces),
        markdown_path: render_markdown(root, surfaces),
        topology_path: topology_source.read_bytes(),
    }
    expected[root / "noetrium/contracts/__init__.py"] = (
        render_root_contract_init(root).encode("utf-8")
    )
    for surface in surfaces:
        if surface.facade_module is None:
            continue
        slug = surface.facade_module.rsplit(".", 1)[-1]
        expected[facade_root / f"{slug}.py"] = render_facade(surface).encode("utf-8")
    for facade_name in _CONVENIENCE_FACADES:
        expected[root / "noetrium/contracts" / f"{facade_name}.py"] = (
            render_convenience_facade(facade_name, surfaces).encode("utf-8")
        )
    readme_block = render_readme_interface_block(surfaces)
    readme_updates: dict[Path, str] = {}
    for readme_path in _readme_paths(root):
        current = readme_path.read_text(encoding="utf-8") if readme_path.is_file() else ""
        if not current.strip():
            raise ValueError(f"README is empty or missing: {readme_path}")
        updated = _replace_readme_interface_block(current, readme_block)
        if check:
            if updated != current:
                ok = False
                print(
                    f"generated README interface catalog drift: {readme_path.relative_to(root)}",
                    file=sys.stderr,
                )
        else:
            readme_updates[readme_path] = updated
    if not check:
        for readme_path, updated in readme_updates.items():
            temporary = readme_path.with_name(readme_path.name + ".tmp")
            temporary.write_text(updated, encoding="utf-8", newline="\n")
            try:
                temporary.replace(readme_path)
            except PermissionError:
                # Windows scanners/editors can deny replace while allowing a direct write.
                # Preserve the generated content and clean up the transient file.
                readme_path.write_text(updated, encoding="utf-8", newline="\n")
                temporary.unlink(missing_ok=True)
        facade_root.mkdir(parents=True, exist_ok=True)
        for path in facade_root.glob("*.py"):
            if path.name == "__init__.py":
                continue
            try:
                if _MARKER not in path.read_text(encoding="utf-8"):
                    continue
            except OSError:
                continue
            if path not in expected:
                path.unlink()
    ok = True
    for path, content in expected.items():
        if not _write_or_check(path, content, check):
            ok = False
            if check:
                print(f"generated contract drift: {path.relative_to(root)}", file=sys.stderr)
    print(json.dumps({
        "schema": SCHEMA,
        "system_count": len(surfaces),
        "facade_count": sum(surface.facade_module is not None for surface in surfaces),
        "api_module_count": sum(len(surface.api_modules) for surface in surfaces),
        "api_symbol_count": sum(
            len(api.symbols) for surface in surfaces for api in surface.api_modules
        ),
        "catalog_digest": hashlib.sha256(expected[catalog_path]).hexdigest(),
        "check": check,
        "readme_changed": [],
        "clean": ok,
    }, sort_keys=True))
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    return generate(args.root.resolve(), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
