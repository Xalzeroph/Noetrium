from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import sys

SCRIPT_DIR = Path(__file__).resolve().parent
ROOT = SCRIPT_DIR.parent
_MARKER = "AUTO-GENERATED by scripts/generate_public_api_hierarchy.py"


def _public_root() -> str:
    return "\n".join(
        [
            f'""" {_MARKER}.',
            "The complete downstream API: one semantic value and one effectful operation.",
            '"""',
            "from noetrium_platform.foundation.kernel.unit import NoetriumUnit",
            "from noetrium._runtime import run",
            "",
            "__all__ = ('NoetriumUnit', 'run')",
            "",
        ]
    )


def _public_stub() -> str:
    return "\n".join(
        [
            "from noetrium_platform.foundation.kernel.unit import NoetriumUnit as NoetriumUnit",
            "from noetrium._runtime import run as run",
            "",
            "__all__: tuple[str, ...]",
            "",
        ]
    )


def _write_or_check(path: Path, content: str, *, check: bool) -> bool:
    expected = content.encode("utf-8")
    current = path.read_bytes() if path.is_file() else None
    if check:
        if current != expected:
            print(f"public API surface drift: {path}", file=sys.stderr)
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    if current != expected:
        path.write_bytes(expected)
    return True


def generate(root: Path, *, check: bool = False) -> int:
    expected = {
        root / "noetrium/__init__.py": _public_root(),
        root / "noetrium/__init__.pyi": _public_stub(),
    }
    ok = True
    for path, content in expected.items():
        ok = _write_or_check(path, content, check=check) and ok

    retired = (
        root / "noetrium/api",
        root / "noetrium/api.py",
        root / "noetrium/api.pyi",
        root / "noetrium_platform/product/api",
        root / "components/api",
        root / "orchestration/api",
    )
    for path in retired:
        if not path.exists():
            continue
        if check:
            print(f"retired public API surface still exists: {path}", file=sys.stderr)
            ok = False
            continue
        if path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
        else:
            path.unlink()

    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    return generate(args.root.resolve(), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
