#!/usr/bin/env python3
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import sys

SCRIPT_DIR = Path(__file__).resolve().parent
ROOT = SCRIPT_DIR.parent
_MARKER = "AUTO-GENERATED by scripts/generate_public_api_hierarchy.py"

def _declared_all(path: Path) -> tuple[str, ...]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        ):
            continue
        raw = ast.literal_eval(node.value)
        if not isinstance(raw, (tuple, list)) or any(
            not isinstance(item, str) or not item.isidentifier()
            for item in raw
        ):
            raise RuntimeError(f"{path}: __all__ must contain identifier strings")
        return tuple(raw)
    raise RuntimeError(f"{path}: top-level Product API must define static __all__")


def discover_product_api_layers(
    root: Path,
) -> tuple[tuple[str, str, tuple[str, ...]], ...]:
    """Discover the unique registry-declared downstream Product authority."""

    catalog = json.loads(
        (root / "noetrium_platform/foundation/governance/system_registry/catalog.json")
        .read_text(encoding="utf-8")
    )
    public = [
        (system_key, row)
        for system_key, row in catalog.items()
        if row.get("downstream_surface") == "public"
    ]
    if len(public) != 1:
        raise RuntimeError(
            f"expected exactly one public downstream authority, got {len(public)}"
        )
    layer, row = public[0]
    package_prefix = row.get("package_prefix")
    if not isinstance(package_prefix, str) or not package_prefix:
        raise RuntimeError("public downstream authority has no package_prefix")
    path = root.joinpath(*package_prefix.split("."), f"{layer}.py")
    symbols = _declared_all(path)
    return ((layer, f"{package_prefix}.{layer}", symbols),)


def _product_layer_wrapper(symbols: tuple[str, ...]) -> str:
    return "\n".join([
        f'""" {_MARKER}.',
        "Internal Product projection of the single downstream Research OS surface.",
        '"""',
        "from __future__ import annotations",
        "",
        "from ..research_os import *  # noqa: F401,F403",
        "",
        f"__all__ = {symbols!r}",
        "",
    ])


def _product_root(symbols: tuple[str, ...]) -> str:
    return "\n".join([
        f'""" {_MARKER}.',
        "Single Product API surface. Lower Product modules are internal interfaces.",
        '"""',
        "from __future__ import annotations",
        "",
        "from ..research_os import *  # noqa: F401,F403",
        "",
        f"__all__ = {symbols!r}",
        "",
    ])


def _public_root(symbols: tuple[str, ...]) -> str:
    public_symbols = (*symbols, "ResearchOS", "open_project")
    return "\n".join([
        f'""" {_MARKER}.',
        "The only downstream API surface: highest-level Research Portfolio / Research OS.",
        '"""',
        "from __future__ import annotations",
        "",
        "from noetrium_platform.product.api import *  # noqa: F401,F403",
        "from noetrium._research_os_runtime import ResearchOS, open_project",
        "",
        f"__all__ = {public_symbols!r}",
        "",
    ])


def _public_stub(symbols: tuple[str, ...]) -> str:
    lines = ["from noetrium_platform.product.api import ("]
    for symbol in symbols:
        lines.append(f"    {symbol} as {symbol},")
    lines.extend([
        ")",
        "from noetrium._research_os_runtime import ResearchOS as ResearchOS, open_project as open_project",
        "",
        "__all__: tuple[str, ...]",
        "",
    ])
    return "\n".join(lines)


def _write_or_check(path: Path, content: str, *, check: bool) -> bool:
    expected = content.encode("utf-8")
    current = path.read_bytes() if path.is_file() else None
    if check:
        if current != expected:
            print(f"public API surface drift: {path}", file=sys.stderr)
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    if current != expected:
        path.write_bytes(expected)
    return True


def generate(root: Path, *, check: bool = False) -> int:
    ((layer, _module, symbols),) = discover_product_api_layers(root)
    product_api = root / "noetrium_platform/product/api"
    public_api = root / "noetrium/api"

    expected: dict[Path, str] = {
        product_api / "__init__.py": _product_root(symbols),
        public_api / "__init__.py": _public_root(symbols),
        public_api / "__init__.pyi": _public_stub(symbols),
    }

    ok = True
    for path, content in expected.items():
        ok = _write_or_check(path, content, check=check) and ok

    legacy = (root / "noetrium/api.py", root / "noetrium/api.pyi")
    for path in legacy:
        if not path.exists():
            continue
        if check:
            print(f"legacy flat public API still exists: {path}", file=sys.stderr)
            ok = False
        else:
            path.unlink()

    expected_product = {path.name for path in expected if path.parent == product_api}
    expected_public = {path.name for path in expected if path.parent == public_api}
    for directory, expected_names in (
        (product_api, expected_product),
        (public_api, expected_public),
    ):
        if not directory.is_dir():
            continue
        for path in directory.iterdir():
            if path.name == "__pycache__" or path.name in expected_names:
                continue
            if path.suffix not in {".py", ".pyi"}:
                continue
            if check:
                print(f"stale public API file: {path}", file=sys.stderr)
                ok = False
            else:
                path.unlink()

    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    return generate(args.root.resolve(), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
