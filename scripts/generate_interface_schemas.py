def generate(root: Path, *, check: bool = False) -> int:
    document = build_document(root)
    expected = (json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    path = root / OUTPUT
    clean = path.is_file() and path.read_bytes() == expected
    if not check and not clean:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        clean = True
    result = {
        "schema": SCHEMA,
        "system_count": len(document["systems"]),
        "api_module_count": sum(len(row["api_modules"]) for row in document["systems"]),
        "api_symbol_count": sum(len(api["symbols"]) for row in document["systems"] for api in row["api_modules"]),
        "interface_digest": hashlib.sha256(expected).hexdigest(),
        "check": check,
        "clean": clean,
    }
    print(json.dumps(result, sort_keys=True))
    return 0 if clean else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    return generate(args.root.resolve(), check=args.check)


