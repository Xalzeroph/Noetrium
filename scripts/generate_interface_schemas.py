def _annotation(node: ast.AST | None) -> str | None:
    return None if node is None else ast.unparse(node)


def _safe_default(node: ast.AST | None) -> str | None:
    if node is None:
        return None
    try:
        return repr(ast.literal_eval(node))
    except (ValueError, TypeError, SyntaxError):
        return ast.unparse(node)


def _parameters(args: ast.arguments) -> list[dict[str, Any]]:
    positional = [*args.posonlyargs, *args.args]
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    rows: list[dict[str, Any]] = []
    for argument, default in zip(positional, defaults):
        rows.append({
            "name": argument.arg,
            "annotation": _annotation(argument.annotation),
            "default": _safe_default(default),
            "required": default is None and argument.arg not in {"self", "cls"},
            "receiver": argument.arg in {"self", "cls"},
            "kind": "positional_only" if argument in args.posonlyargs else "positional_or_keyword",
        })
    if args.vararg is not None:
        rows.append({
            "name": args.vararg.arg,
            "annotation": _annotation(args.vararg.annotation),
            "default": None,
            "required": False,
            "receiver": False,
            "kind": "var_positional",
        })
    for argument, default in zip(args.kwonlyargs, args.kw_defaults):
        rows.append({
            "name": argument.arg,
            "annotation": _annotation(argument.annotation),
            "default": _safe_default(default),
            "required": default is None,
            "receiver": False,
            "kind": "keyword_only",
        })
    if args.kwarg is not None:
        rows.append({
            "name": args.kwarg.arg,
            "annotation": _annotation(args.kwarg.annotation),
            "default": None,
            "required": False,
            "receiver": False,
            "kind": "var_keyword",
        })
    return rows


def _callable(node: ast.FunctionDef | ast.AsyncFunctionDef, kind: str) -> dict[str, Any]:
    return {
        "schema_id": INTERFACE_SCHEMA_ID,
        "schema_version": INTERFACE_SCHEMA_VERSION,
        "name": node.name,
        "kind": kind,
        "signature": ast.unparse(node).splitlines()[0],
        "parameters": _parameters(node.args),
        "return_annotation": _annotation(node.returns),
        "decorators": [ast.unparse(value) for value in node.decorator_list],
        "doc": ast.get_docstring(node),
    }


def _class(node: ast.ClassDef, *, public_methods_only: bool = False) -> dict[str, Any]:
    methods: list[dict[str, Any]] = []
    fields: list[dict[str, Any]] = []
    members: list[str] = []
    for child in node.body:
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if public_methods_only and child.name.startswith("_"):
                continue
            methods.append(_callable(child, "method"))
        elif (
            isinstance(child, ast.AnnAssign)
            and isinstance(child.target, ast.Name)
            and not child.target.id.startswith("_")
        ):
            fields.append({
                "name": child.target.id,
                "annotation": _annotation(child.annotation),
                "default": _safe_default(child.value),
            })
        elif isinstance(child, ast.Assign):
            for target in child.targets:
                if isinstance(target, ast.Name) and not target.id.startswith("_"):
                    members.append(target.id)
    return {
        "schema_id": INTERFACE_SCHEMA_ID,
        "schema_version": INTERFACE_SCHEMA_VERSION,
        "name": node.name,
        "kind": "class",
        "bases": [ast.unparse(value) for value in node.bases],
        "decorators": [ast.unparse(value) for value in node.decorator_list],
        "fields": fields,
        "members": members,
        "methods": methods,
        "doc": ast.get_docstring(node),
    }


def _reexport_source(root: Path, source: Path, module: str) -> Path | None:
    if module.startswith("."):
        level = len(module) - len(module.lstrip("."))
        suffix = module[level:]
        base = source.parent
        for _ in range(level - 1):
            base = base.parent
        target = base.joinpath(*suffix.split(".")) if suffix else base
    else:
        target = root.joinpath(*module.split("."))
    file_path = target.with_suffix(".py")
    if file_path.is_file():
        return file_path
    init_path = target / "__init__.py"
    return init_path if init_path.is_file() else None


def _symbols(
    root: Path,
    path: Path,
    names: tuple[str, ...],
    *,
    seen: frozenset[tuple[Path, str]] = frozenset(),
    public_methods_only: bool = False,
) -> tuple[dict[str, Any], ...]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    definitions: dict[str, ast.AST] = {}
    reexports: dict[str, tuple[str, str]] = {}
    star_reexports: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            definitions[node.name] = node
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else (node.target,)
            for target in targets:
                if isinstance(target, ast.Name):
                    definitions[target.id] = node
        elif isinstance(node, ast.ImportFrom):
            module = "." * node.level + (node.module or "")
            for alias in node.names:
                if alias.name == "*":
                    star_reexports.append(module)
                else:
                    reexports[alias.asname or alias.name] = (module, alias.name)

    result: list[dict[str, Any]] = []
    for name in names:
        node = definitions.get(name)
        if isinstance(node, ast.ClassDef):
            result.append(_class(node, public_methods_only=public_methods_only))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            result.append(_callable(node, "async_function" if isinstance(node, ast.AsyncFunctionDef) else "function"))
        elif node is not None:
            result.append({
                "schema_id": INTERFACE_SCHEMA_ID,
                "schema_version": INTERFACE_SCHEMA_VERSION,
                "name": name,
                "kind": "value",
                "annotation": _annotation(node.annotation) if isinstance(node, ast.AnnAssign) else None,
                "value": _safe_default(node.value),
                "doc": None,
            })
        elif name in reexports:
            module, origin_name = reexports[name]
            row: dict[str, Any] = {
                "schema_id": INTERFACE_SCHEMA_ID,
                "schema_version": INTERFACE_SCHEMA_VERSION,
                "name": name,
                "kind": "reexport",
                "origin_module": module,
                "origin_name": origin_name,
                "doc": None,
            }
            source = _reexport_source(root, path, module)
            key = (source.resolve(), origin_name) if source is not None else None
            if source is not None and key not in seen:
                row["resolved_schema"] = _symbols(
                    root,
                    source,
                    (origin_name,),
                    seen=seen | {key},
                    public_methods_only=public_methods_only,
                )[0]
            result.append(row)
        else:
            resolved_star: dict[str, Any] | None = None
            for module in star_reexports:
                source = _reexport_source(root, path, module)
                key = (
                    (source.resolve(), name)
                    if source is not None
                    else None
                )
                if source is None or key in seen:
                    continue
                candidate = _symbols(
                    root,
                    source,
                    (name,),
                    seen=seen | {key},
                    public_methods_only=public_methods_only,
                )[0]
                if candidate.get("kind") != "unknown":
                    resolved_star = {
                        "schema_id": INTERFACE_SCHEMA_ID,
                        "schema_version": INTERFACE_SCHEMA_VERSION,
                        "name": name,
                        "kind": "reexport",
                        "origin_module": module,
                        "origin_name": name,
                        "resolved_schema": candidate,
                        "doc": None,
                    }
                    break
            if resolved_star is not None:
                result.append(resolved_star)
            else:
                result.append({
                    "schema_id": INTERFACE_SCHEMA_ID,
                    "schema_version": INTERFACE_SCHEMA_VERSION,
                    "name": name,
                    "kind": "unknown",
                    "doc": None,
                })
    return tuple(result)


def _public_symbol(
    root: Path,
    path: Path,
    name: str,
) -> dict[str, Any]:
    return _symbols(
        root,
        path,
        (name,),
        public_methods_only=True,
    )[0]


def _literal_all(path: Path) -> tuple[str, ...]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets):
            continue
        raw = ast.literal_eval(node.value)
        if not isinstance(raw, (tuple, list)) or any(not isinstance(item, str) for item in raw):
            raise RuntimeError(f"{path}: __all__ must be a literal string sequence")
        return tuple(raw)
    raise RuntimeError(f"{path}: missing literal __all__")


def _digest(value: object) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


def _semantic_trait_catalog(root: Path) -> dict[str, dict[str, object]]:
    """Merge Product-owned vocabulary contracts with Composition-owned lowering."""

    trait_source = root / "noetrium_platform/product/research_traits.py"
    trait_tree = ast.parse(
        trait_source.read_text(encoding="utf-8"), filename=str(trait_source)
    )
    constants: dict[str, str] = {}
    assignments: dict[str, ast.AST] = {}
    for node in trait_tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        assignments[target.id] = node.value
        if (
            target.id.startswith("TRAIT_")
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            constants[target.id] = node.value.value

    def named_set(name: str) -> frozenset[str]:
        value = assignments[name]
        if isinstance(value, ast.Call) and value.args:
            value = value.args[0]
        if not isinstance(value, (ast.Set, ast.Tuple, ast.List)):
            raise RuntimeError(f"{name} must remain a literal trait collection")
        rows: set[str] = set()
        for item in value.elts:
            if not isinstance(item, ast.Name) or item.id not in constants:
                raise RuntimeError(f"{name} contains non-canonical trait reference")
            rows.add(constants[item.id])
        return frozenset(rows)

    raw_contracts = assignments.get("_TRAIT_CONTRACT_SPEC")
    if not isinstance(raw_contracts, ast.Dict):
        raise RuntimeError("_TRAIT_CONTRACT_SPEC must remain a literal mapping")
    contracts: dict[str, dict[str, object]] = {}
    for key, value in zip(raw_contracts.keys, raw_contracts.values):
        if not isinstance(key, ast.Name) or key.id not in constants:
            raise RuntimeError("trait contract contains non-canonical trait key")
        if not isinstance(value, ast.Dict):
            raise RuntimeError("trait contract value must remain a literal mapping")
        decoded = ast.literal_eval(value)
        required = {
            "locations",
            "recognized_parameters",
            "structured_parameters",
            "exclusive_parameter_groups",
        }
        if not isinstance(decoded, dict) or set(decoded) != required:
            raise RuntimeError("trait contract has invalid shape")
        contracts[constants[key.id]] = {
            "locations": tuple(decoded["locations"]),
            "recognized_parameters": tuple(decoded["recognized_parameters"]),
            "structured_parameters": tuple(decoded["structured_parameters"]),
            "exclusive_parameter_groups": tuple(
                tuple(group) for group in decoded["exclusive_parameter_groups"]
            ),
            "open_parameters": True,
        }
    if set(contracts) != set(constants.values()):
        missing = sorted(set(constants.values()) - set(contracts))
        raise RuntimeError(f"built-in traits missing authoring contracts: {missing}")

    lowering_source = root / "noetrium_platform/composition/research_semantics.py"
    lowering_tree = ast.parse(
        lowering_source.read_text(encoding="utf-8"), filename=str(lowering_source)
    )
    lowering_assignment: ast.AST | None = None
    for node in lowering_tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "_NODE_LOWERING"
        ):
            lowering_assignment = node.value
            break
    if isinstance(lowering_assignment, ast.Call) and lowering_assignment.args:
        lowering_assignment = lowering_assignment.args[0]
    if not isinstance(lowering_assignment, ast.Dict):
        raise RuntimeError("_NODE_LOWERING must remain a literal mapping")
    lowering: dict[str, tuple[str, str | None]] = {}
    for key, value in zip(lowering_assignment.keys, lowering_assignment.values):
        if not isinstance(key, ast.Name) or key.id not in constants:
            raise RuntimeError("_NODE_LOWERING contains non-canonical trait key")
        if not isinstance(value, ast.Call) or not value.args:
            raise RuntimeError("_NODE_LOWERING value must be ResearchTraitLowering")
        mode_node = value.args[0]
        if not isinstance(mode_node, ast.Constant) or not isinstance(mode_node.value, str):
            raise RuntimeError("ResearchTraitLowering mode must stay literal")
        domain = None
        if len(value.args) > 1:
            domain_node = value.args[1]
            if not isinstance(domain_node, ast.Constant) or not isinstance(
                domain_node.value, str
            ):
                raise RuntimeError(
                    "ResearchTraitLowering domain must stay literal text"
                )
            domain = domain_node.value
        lowering[constants[key.id]] = (mode_node.value, domain)

    platform = named_set("PLATFORM_BINDING_TRAITS")
    metadata = named_set("SCIENTIFIC_METADATA_TRAITS")
    result: dict[str, dict[str, object]] = {}
    for trait_id in sorted(constants.values()):
        mode, domain = lowering.get(trait_id, (None, None))
        if trait_id in metadata:
            role = "scientific_metadata"
        elif trait_id in platform:
            role = "platform_requirement"
        elif trait_id == "research.metric":
            role = "declarative_scientific_symbol"
        elif mode is not None:
            role = "executable_semantic"
        else:
            role = "semantic"
        result[trait_id] = {
            "role": role,
            "lowering_mode": mode,
            "domain": domain,
            "parameter_authority": "graph/symbol parameters",
            "authoring_contract": contracts[trait_id],
        }
    return result


